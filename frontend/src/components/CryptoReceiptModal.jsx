// =============================================================================
// ChronoSync 3D — Cryptographic Proof of Submission Modal (CryptoReceiptModal.jsx)
// =============================================================================
// Luxury 3D Glassmorphic Digital Receipt Certificate
// Features:
//   - Official CHRONOSYNC CRYPTO-SEAL with rotating 3D shield
//   - Server-Side Millisecond Timestamp (Anti-Clock Tampering)
//   - 64-Character SHA-256 Cryptographic Digest
//   - 1-Click Copy Hash & Download Digital Receipt (.TXT)
//   - Submitted PDF Document Link (if attached)
//   - Non-Repudiation Certificate Seal & Verification Counter
// =============================================================================

import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  ShieldCheck, Copy, Check, Download, FileText, ExternalLink,
  Clock, Calendar, User, Award, Hash, X, CheckCircle2, AlertCircle, Sparkles
} from 'lucide-react';

export default function CryptoReceiptModal({ isOpen, onClose, receipt }) {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !receipt) return null;

  const hash = receipt.receipt_hash || receipt.sha256_receipt_hash || 'SHA256_CRYPTOGRAPHIC_SIGNATURE_NOT_FOUND';
  const timestamp = receipt.server_timestamp_ms || receipt.completed_at || 'Recorded on Server';
  const status = receipt.status || (receipt.is_on_time ? 'Completed' : 'Completed');
  const isOnTime = status === 'Completed' || receipt.is_on_time;
  const studentName = receipt.student_name || 'Enrolled Student';
  const studentEmail = receipt.student_email || 'student@edutrack.ac';
  const courseCode = receipt.course_code || 'CS202';
  const courseName = receipt.course_name || 'Academic Coursework';
  const taskTitle = receipt.assignment_title || receipt.title || 'Assignment Submission';
  const dueDate = receipt.official_due_date || receipt.due_date || 'Standard Academic Due Date';
  const verificationCount = receipt.verification_count || 0;
  const fileName = receipt.file_name;
  const filePath = receipt.file_path;

  const handleCopy = () => {
    navigator.clipboard.writeText(hash);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadTxt = () => {
    const certText = `
================================================================================
          CHRONOSYNC 3D — OFFICIAL CRYPTOGRAPHIC PROOF OF SUBMISSION
================================================================================
INTEGRITY SEAL  : CHRONOSYNC-SHA256-GENUINE-RECEIPT
SECURITY STATUS : 100% AUTHENTIC & UNTAMPERED (NON-REPUDIATION GUARANTEED)
--------------------------------------------------------------------------------

[STUDENT IDENTITY]
Student Name       : ${studentName}
Student Email      : ${studentEmail}
Department         : ${receipt.department || 'School of Computer Science & Engineering'}
Program            : ${receipt.program || 'B.Tech Computer Science & Engineering'}
Semester           : ${receipt.semester || 'Semester 3'}

[COURSEWORK DELIVERABLE]
Assignment Title   : ${taskTitle}
Course Code        : ${courseCode}
Course Name        : ${courseName}
Official Due Date  : ${dueDate}
Submitted PDF File : ${fileName || 'Digital Task Mark Done (No PDF Attachment)'}

[CRYPTOGRAPHIC TIMESTAMP & SIGNATURE]
Server Timestamp   : ${timestamp} (Exact UTC/IST Server Clock down to Milliseconds)
Submission Verdict : ${isOnTime ? 'ON-TIME SUBMISSION (COMPLIANT)' : 'LATE SUBMISSION'}
Verification Count : Verified ${verificationCount} time(s) by Faculty / HOD

SHA-256 DIGITAL RECEIPT HASH (64-CHAR HEX DIGEST):
${hash}

--------------------------------------------------------------------------------
CANONICAL VERIFICATION FORMULA:
SHA-256(student_id|student_email|deadline_id|server_timestamp_ms|status|SERVER_SALT)

This digital receipt was generated by ChronoSync's backend cryptographic vault.
Any client-side DOM modification, timestamp forgery, or inspection element manipulation
is mathematically rendered impossible via SHA-256 Avalanche Effect integrity checking.
================================================================================
Generated on: ${new Date().toUTCString()}
`;

    const blob = new Blob([certText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `ChronoSync_Receipt_${taskTitle.replace(/[^a-zA-Z0-9_-]/g, '_')}_${hash.slice(0, 8)}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <AnimatePresence>
      <div
        style={{
          position: 'fixed',
          inset: 0,
          zIndex: 9999,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          padding: '20px',
          background: 'rgba(5, 5, 10, 0.78)',
          backdropFilter: 'blur(12px)',
        }}
        onClick={onClose}
      >
        <motion.div
          initial={{ opacity: 0, scale: 0.92, y: 20 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.92, y: 20 }}
          transition={{ type: 'spring', damping: 25, stiffness: 300 }}
          onClick={(e) => e.stopPropagation()}
          style={{
            width: '100%',
            maxWidth: '680px',
            maxHeight: '90vh',
            overflowY: 'auto',
            background: 'linear-gradient(135deg, rgba(22, 27, 34, 0.96) 0%, rgba(13, 17, 23, 0.98) 100%)',
            border: '1px solid rgba(16, 185, 129, 0.35)',
            boxShadow: '0 25px 70px rgba(0, 0, 0, 0.7), 0 0 35px rgba(16, 185, 129, 0.18)',
            borderRadius: '20px',
            padding: '30px',
            color: '#f0f6fc',
            position: 'relative',
          }}
        >
          {/* Close Button */}
          <button
            onClick={onClose}
            style={{
              position: 'absolute',
              top: '18px',
              right: '18px',
              background: 'rgba(255, 255, 255, 0.06)',
              border: '1px solid rgba(255, 255, 255, 0.12)',
              borderRadius: '50%',
              width: '34px',
              height: '34px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              color: '#8b949e',
              cursor: 'pointer',
              transition: 'all 0.2s',
            }}
            onMouseEnter={(e) => { e.currentTarget.style.color = '#fff'; e.currentTarget.style.background = 'rgba(255, 255, 255, 0.15)'; }}
            onMouseLeave={(e) => { e.currentTarget.style.color = '#8b949e'; e.currentTarget.style.background = 'rgba(255, 255, 255, 0.06)'; }}
          >
            <X size={16} />
          </button>

          {/* Certificate Header with 3D Rotating Shield */}
          <div style={{ textAlign: 'center', marginBottom: '22px' }}>
            <motion.div
              animate={{
                rotateY: [0, 360],
              }}
              transition={{
                duration: 8,
                repeat: Infinity,
                ease: 'linear',
              }}
              style={{
                width: '64px',
                height: '64px',
                borderRadius: '50%',
                background: 'radial-gradient(circle, rgba(16, 185, 129, 0.3) 0%, rgba(5, 150, 105, 0.1) 70%)',
                border: '1.5px solid #10b981',
                boxShadow: '0 0 25px rgba(16, 185, 129, 0.5)',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                margin: '0 auto 14px',
                perspective: '1000px',
              }}
            >
              <ShieldCheck size={32} color="#10b981" />
            </motion.div>

            <div style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '6px',
              padding: '3px 12px',
              borderRadius: '20px',
              background: 'rgba(16, 185, 129, 0.15)',
              border: '1px solid rgba(16, 185, 129, 0.4)',
              fontSize: '11px',
              fontFamily: 'var(--font-mono, monospace)',
              fontWeight: 700,
              color: '#34d399',
              letterSpacing: '0.08em',
              textTransform: 'uppercase',
              marginBottom: '6px',
            }}>
              <Sparkles size={12} />
              CHRONOSYNC CRYPTO-SEAL · VERIFIED GENUINE
            </div>

            <h2 style={{
              fontSize: '22px',
              fontWeight: 700,
              letterSpacing: '-0.02em',
              margin: '0 0 4px',
              color: '#ffffff',
            }}>
              Cryptographic Proof of Submission
            </h2>
            <p style={{ fontSize: '13px', color: '#8b949e', margin: 0 }}>
              Tamper-proof digital receipt mathematically bound via SHA-256 non-repudiation
            </p>
          </div>

          {/* Metadata Grid */}
          <div style={{
            display: 'grid',
            gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))',
            gap: '12px',
            marginBottom: '20px',
          }}>
            {/* Student Info Card */}
            <div style={{
              background: 'rgba(255, 255, 255, 0.03)',
              border: '1px solid rgba(255, 255, 255, 0.08)',
              borderRadius: '12px',
              padding: '14px',
            }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px', color: '#10b981' }}>
                <User size={15} />
                <span style={{ fontSize: '12px', fontWeight: 600, letterSpacing: '0.04em' }}>STUDENT IDENTITY</span>
              </div>
              <div style={{ fontSize: '14px', fontWeight: 600, color: '#f0f6fc' }}>{studentName}</div>
              <div style={{ fontSize: '12px', color: '#8b949e', fontFamily: 'var(--font-mono, monospace)' }}>{studentEmail}</div>
              <div style={{ fontSize: '11px', color: '#6e7681', marginTop: '4px' }}>
                {receipt.department || 'Computer Science'} · {receipt.program || 'Core CSE'}
              </div>
            </div>

            {/* Course & Deliverable */}
            <div style={{
              background: 'rgba(255, 255, 255, 0.03)',
              border: '1px solid rgba(255, 255, 255, 0.08)',
              borderRadius: '12px',
              padding: '14px',
            }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px', color: '#38bdf8' }}>
                <Award size={15} />
                <span style={{ fontSize: '12px', fontWeight: 600, letterSpacing: '0.04em' }}>ACADEMIC COURSEWORK</span>
              </div>
              <div style={{ fontSize: '14px', fontWeight: 600, color: '#f0f6fc' }}>{taskTitle}</div>
              <div style={{ fontSize: '12px', color: '#38bdf8', fontWeight: 500 }}>
                {courseCode} · {courseName}
              </div>
              <div style={{ fontSize: '11px', color: '#6e7681', marginTop: '4px' }}>
                Official Due Date: {dueDate}
              </div>
            </div>
          </div>

          {/* Exact Millisecond Server Timestamp Card */}
          <div style={{
            background: 'rgba(16, 185, 129, 0.06)',
            border: '1px solid rgba(16, 185, 129, 0.25)',
            borderRadius: '12px',
            padding: '14px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            gap: '12px',
            flexWrap: 'wrap',
            marginBottom: '20px',
          }}>
            <div>
              <div style={{ display: 'flex', alignItems: 'center', gap: '6px', fontSize: '11px', color: '#10b981', fontWeight: 700, textTransform: 'uppercase', letterSpacing: '0.06em' }}>
                <Clock size={13} />
                <span>SERVER TIMESTAMP (ACCURACY: ±1 MS)</span>
              </div>
              <div style={{
                fontSize: '15px',
                fontFamily: 'var(--font-mono, monospace)',
                fontWeight: 700,
                color: '#ffffff',
                marginTop: '4px',
              }}>
                {timestamp}
              </div>
              <div style={{ fontSize: '11px', color: '#8b949e', marginTop: '2px' }}>
                Server-side stamped (Client clock manipulation neutralized)
              </div>
            </div>

            <div style={{
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'flex-end',
              gap: '4px',
            }}>
              <span style={{
                display: 'inline-flex',
                alignItems: 'center',
                gap: '5px',
                padding: '4px 12px',
                borderRadius: '8px',
                background: isOnTime ? 'rgba(16, 185, 129, 0.2)' : 'rgba(239, 68, 68, 0.2)',
                border: isOnTime ? '1px solid #10b981' : '1px solid #ef4444',
                color: isOnTime ? '#34d399' : '#f87171',
                fontSize: '12px',
                fontFamily: 'var(--font-mono, monospace)',
                fontWeight: 700,
              }}>
                {isOnTime ? <CheckCircle2 size={13} /> : <AlertCircle size={13} />}
                {isOnTime ? 'ON-TIME SUBMISSION' : 'LATE SUBMISSION'}
              </span>
              <span style={{ fontSize: '10.5px', color: '#8b949e' }}>
                Verified {verificationCount} time{verificationCount === 1 ? '' : 's'} by Faculty
              </span>
            </div>
          </div>

          {/* SHA-256 Receipt Hash Box */}
          <div style={{ marginBottom: '20px' }}>
            <div style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              marginBottom: '6px',
            }}>
              <span style={{
                fontSize: '11px',
                fontFamily: 'var(--font-mono, monospace)',
                color: '#f59e0b',
                fontWeight: 700,
                letterSpacing: '0.06em',
                display: 'flex',
                alignItems: 'center',
                gap: '5px',
              }}>
                <Hash size={13} />
                SHA-256 TAMPER-PROOF DIGITAL RECEIPT SIGNATURE
              </span>
              <span style={{ fontSize: '11px', color: '#6e7681', fontFamily: 'var(--font-mono, monospace)' }}>
                64 HEX DIGITS
              </span>
            </div>

            <div style={{
              background: '#090d16',
              border: '1px solid rgba(245, 158, 11, 0.3)',
              borderRadius: '10px',
              padding: '12px 14px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: '10px',
            }}>
              <div style={{
                fontFamily: 'var(--font-mono, monospace)',
                fontSize: '12px',
                color: '#fde68a',
                letterSpacing: '0.04em',
                wordBreak: 'break-all',
                lineHeight: '1.4',
                userSelect: 'all',
              }}>
                {hash}
              </div>
              <button
                onClick={handleCopy}
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: '6px',
                  padding: '7px 12px',
                  borderRadius: '6px',
                  background: copied ? 'rgba(16, 185, 129, 0.2)' : 'rgba(255, 255, 255, 0.08)',
                  border: copied ? '1px solid #10b981' : '1px solid rgba(255, 255, 255, 0.15)',
                  color: copied ? '#34d399' : '#ffffff',
                  fontSize: '11px',
                  fontFamily: 'var(--font-mono, monospace)',
                  fontWeight: 600,
                  cursor: 'pointer',
                  flexShrink: 0,
                  transition: 'all 0.2s',
                }}
              >
                {copied ? <Check size={13} /> : <Copy size={13} />}
                {copied ? 'Copied' : 'Copy Hash'}
              </button>
            </div>
          </div>

          {/* Attached PDF Work Display (if any) */}
          {filePath && (
            <div style={{
              background: 'rgba(56, 189, 248, 0.08)',
              border: '1px solid rgba(56, 189, 248, 0.25)',
              borderRadius: '10px',
              padding: '11px 14px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              marginBottom: '20px',
            }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
                <FileText size={16} color="#38bdf8" />
                <div>
                  <div style={{ fontSize: '12.5px', fontWeight: 600, color: '#f0f6fc' }}>
                    {fileName || 'Submitted Assignment Document.pdf'}
                  </div>
                  <div style={{ fontSize: '11px', color: '#8b949e' }}>
                    Archived PDF work linked to this cryptographic signature
                  </div>
                </div>
              </div>
              <a
                href={filePath}
                target="_blank"
                rel="noopener noreferrer"
                download
                style={{
                  display: 'inline-flex',
                  alignItems: 'center',
                  gap: '5px',
                  padding: '6px 12px',
                  borderRadius: '6px',
                  background: 'rgba(56, 189, 248, 0.15)',
                  border: '1px solid rgba(56, 189, 248, 0.4)',
                  color: '#38bdf8',
                  fontSize: '11.5px',
                  fontWeight: 600,
                  textDecoration: 'none',
                  transition: 'all 0.2s',
                }}
              >
                <Download size={12} />
                <span>Download PDF</span>
              </a>
            </div>
          )}

          {/* Action Buttons */}
          <div style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end', marginTop: '10px' }}>
            <button
              onClick={handleDownloadTxt}
              style={{
                display: 'inline-flex',
                alignItems: 'center',
                gap: '7px',
                padding: '9px 16px',
                borderRadius: '8px',
                background: 'rgba(255, 255, 255, 0.08)',
                border: '1px solid rgba(255, 255, 255, 0.18)',
                color: '#ffffff',
                fontSize: '12.5px',
                fontWeight: 600,
                cursor: 'pointer',
                transition: 'all 0.2s',
              }}
              onMouseEnter={(e) => { e.currentTarget.style.background = 'rgba(255, 255, 255, 0.14)'; }}
              onMouseLeave={(e) => { e.currentTarget.style.background = 'rgba(255, 255, 255, 0.08)'; }}
            >
              <Download size={14} />
              Download Digital Receipt (.TXT)
            </button>

            <button
              onClick={onClose}
              style={{
                display: 'inline-flex',
                alignItems: 'center',
                gap: '7px',
                padding: '9px 20px',
                borderRadius: '8px',
                background: 'linear-gradient(135deg, #10b981 0%, #059669 100%)',
                border: 'none',
                color: '#ffffff',
                fontSize: '12.5px',
                fontWeight: 700,
                cursor: 'pointer',
                boxShadow: '0 4px 15px rgba(16, 185, 129, 0.35)',
                transition: 'all 0.2s',
              }}
              onMouseEnter={(e) => { e.currentTarget.style.transform = 'translateY(-1px)'; }}
              onMouseLeave={(e) => { e.currentTarget.style.transform = 'none'; }}
            >
              Close Certificate
            </button>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
}
